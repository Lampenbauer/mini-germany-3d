#!/usr/bin/env node
/**
 * Copies the static CesiumJS assets (Workers, Widgets, Assets, ThirdParty)
 * to public/cesium – from there they are served under /cesium by the dev
 * server and in the build (see CESIUM_BASE_URL in src/map/cesium-base.ts).
 *
 * Runs automatically as a postinstall hook.
 */

import { cpSync, existsSync, mkdirSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = dirname(fileURLToPath(import.meta.url))
const source = resolve(__dirname, '../node_modules/cesium/Build/Cesium')
const target = resolve(__dirname, '../public/cesium')

if (!existsSync(source)) {
  console.error('❌ node_modules/cesium/Build/Cesium not found – run `npm install` first.')
  process.exit(1)
}

mkdirSync(target, { recursive: true })
for (const dir of ['Workers', 'ThirdParty', 'Assets', 'Widgets']) {
  cpSync(resolve(source, dir), resolve(target, dir), { recursive: true })
}
writeFileSync(
  resolve(target, '.gitkeep-note.txt'),
  'This directory is generated by scripts/copy-cesium-assets.mjs (postinstall) and is not checked in.\n',
)
console.log(`✅ Copied Cesium assets to ${target}`)
